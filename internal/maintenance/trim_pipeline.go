// trimClock is the encoder clock for a trim. A cut seeks to a midpoint, so every kept frame arrives
// half a frame off the source's own frame-rate clock, and rounding to that clock gives neighbouring
// frames the same timestamp. 90 kHz is fine enough that none round together.
const trimClock = "1:90000"

// trimInputArgs opens src as inputArgs does, seeking to the range first. -ss before -i decodes
// from the preceding keyframe and drops frames before the seek, so the cut lands on any frame.
// -seek_timestamp makes -ss and -to the file's own times: ffmpeg would otherwise add the container's
// start time, which audio priming makes negative, and land a frame early.
func trimInputArgs(demuxer, src string, r trimRange) []string {
	args := []string{"-nostdin", "-y", "-loglevel", "error"}
	if r.HasSeek || r.HasStop {
		args = append(args, "-seek_timestamp", "1")
	}
	if r.HasSeek {
		args = append(args, "-ss", fmtTime(r.Seek))
	}
	if r.HasStop {
		args = append(args, "-to", fmtTime(r.Stop))
	}
	return append(args, "-protocol_whitelist", "file", "-f", demuxer, "-i", toolArg(src))
}

// TrimMP4Args builds the one ffmpeg pass for an MP4/MOV trim: the same seek on every stream, the
// main video re-encoded, the rest copied. -copypriorss 0 stops ffmpeg copying the audio packets
// between the keyframe it seeks to and the cut, which would leave them before the first frame.
// chaptersFile is "" when no chapter survives the cut.
func TrimMP4Args(p Probe, available map[string]bool, format, src, dst, chaptersFile string, r trimRange) ([]string, error) {
	v, ok := p.MainVideo()
	if !ok {
		return nil, refuse(ReasonNoVideo, "")
	}
	spec := "v:" + strconv.Itoa(p.VideoOrdinal(v))
	enc, err := EncoderArgs(v, spec, available)
	if err != nil {
		return nil, err
	}
	args := trimInputArgs("mov", src, r)
	chapterMap := "-1"
	if chaptersFile != "" {
		args = append(args, "-protocol_whitelist", "file", "-f", "ffmetadata", "-i", toolArg(chaptersFile))
		chapterMap = "1"
	}
	var names, covers []string
	out := 0
	for _, s := range p.Streams {
		if isQTChapterTrack(s) { // regenerated by -map_chapters, or gone with the last chapter
			continue
		}
		if n, ok := s.Tags["name"]; ok && s.Tags["title"] == "" {
			names = append(names, "-metadata:s:"+strconv.Itoa(out), "title="+n)
		}
		args = append(args, "-map", "0:"+strconv.Itoa(s.Index))
		// Cover art's one packet sits at time zero, and it isn't part of the timeline.
		if s.Disposition["attached_pic"] != 0 {
			covers = append(covers, "-copypriorss:"+strconv.Itoa(out), "1")
		}
		out++
	}
	args = append(args, "-c", "copy", "-copypriorss", "0")
	args = append(args, covers...)
	args = append(args, names...)
	args = append(args, enc...)
	args = append(args, "-enc_time_base:"+spec, trimClock)
	if e := v.Tags["encoder"]; e != "" {
		args = append(args, "-metadata:s:"+spec, "encoder="+e)
	}
	return append(args, "-map_metadata", "0", "-map_chapters", chapterMap, "-fflags", "+bitexact",
		"-movflags", "+faststart", "-f", format, toolArg(dst)), nil
}

// isFLAC reports whether s is a FLAC audio track. mkvmerge can't split one, so a Matroska trim
// re-encodes it beside the video instead: FLAC is lossless, so its samples come out bit for bit, and
// the accurate seek cuts it on the sample rather than the packet.
func isFLAC(s Stream) bool { return s.CodecType == "audio" && s.CodecName == "flac" }

// trimEncoded lists the tracks step 1 writes, in the intermediate's track order: the main video,
// then each FLAC track. p must have a main video.
func trimEncoded(p Probe) []Stream {
	v, _ := p.MainVideo()
	out := []Stream{v}
	for _, s := range p.Streams {
		if isFLAC(s) {
			out = append(out, s)
		}
	}
	return out
}

// TrimMKVEncodeArgs builds step 1 for a Matroska trim: the kept range of the main video track,
// re-encoded, and of each FLAC track, re-encoded losslessly, into an intermediate with no tags or
// chapters of its own.
func TrimMKVEncodeArgs(p Probe, available map[string]bool, src, intermediate string, r trimRange) ([]string, error) {
	v, ok := p.MainVideo()
	if !ok {
		return nil, refuse(ReasonNoVideo, "")
	}
	enc, err := EncoderArgs(v, "v:0", available)
	if err != nil {
		return nil, err
	}
	args := trimInputArgs("matroska", src, r)
	encoded := trimEncoded(p)
	for _, s := range encoded {
		args = append(args, "-map", "0:"+strconv.Itoa(s.Index))
	}
	args = append(args, enc...)
	args = append(args, "-enc_time_base:v:0", trimClock)
	if len(encoded) > 1 {
		// Without -strict experimental the encoder writes a 32-bit source at 24 bits.
		args = append(args, "-c:a", "flac", "-strict:a", "experimental")
	}
	return append(args, "-map_metadata", "-1", "-map_chapters", "-1",
		"-fflags", "+bitexact", "-f", "matroska", toolArg(intermediate)), nil
}

// otherTracks counts the Matroska tracks left for step 2 to cut: neither the main video nor FLAC.
func otherTracks(p Probe) int {
	v, _ := p.MainVideo()
	n := 0
	for _, s := range p.Streams {
		if s.CodecType != "attachment" && s.Index != v.Index && !isFLAC(s) {
			n++
		}
	}
	return n
}

// TrimMKVCutArgs builds step 2: every track step 1 didn't encode, cut on packets. With no video
// track left mkvmerge can split at any packet rather than at a keyframe. This must be its own
// pass: --split applies to a whole output, and the re-encoded tracks are already the kept range.
// Attachments and global tags stay on this file; step 3 carries them.
func TrimMKVCutArgs(p Probe, src, cut string, r trimRange) []string {
	v, _ := p.MainVideo()
	var from, to string
	if r.HasSeek {
		from = hmsTime(r.Seek)
	}
	if r.HasStop {
		to = hmsTime(r.Stop)
	}
	args := []string{"-o", toolArg(cut), "--no-date"}
	if !hasTrackStatistics(p) {
		args = append(args, "--disable-track-statistics-tags")
	}
	args = append(args, "--split", "parts:"+from+"-"+to, "--no-chapters",
		"-d", "!"+strconv.Itoa(mkvTrackID(p, v)))
	var flac []string
	for _, s := range trimEncoded(p)[1:] {
		flac = append(flac, strconv.Itoa(mkvTrackID(p, s)))
	}
	if len(flac) > 0 {
		args = append(args, "-a", "!"+strings.Join(flac, ","))
	}
	return append(args, toolArg(src))
}

// TrimMKVMergeArgs builds step 3: dst is the cut tracks plus the re-encoded ones, each put back in
// the original's position with its name, language, flags and tags (trackTags, aligned with
// trimEncoded; "" for a track with none). base is step 2's file, or the original with every track
// dropped when nothing was left to cut, whose tags and attachments still carry. A cut file
// renumbers its tracks without the re-encoded ones, so the order is rebuilt rather than reused.
// chaptersFile is "" when no chapter survives the cut.
func TrimMKVMergeArgs(p Probe, base string, baseHasTracks bool, intermediate string, trackTags []string, chaptersFile, dst string) []string {
	encoded := trimEncoded(p)
	at := make(map[int]int, len(encoded)) // stream index → intermediate track id
	for i, s := range encoded {
		at[s.Index] = i
	}
	var order []string
	next := 0
	for _, s := range p.Streams {
		if s.CodecType == "attachment" {
			continue
		}
		if i, ok := at[s.Index]; ok {
			order = append(order, "1:"+strconv.Itoa(i))
			continue
		}
		order = append(order, "0:"+strconv.Itoa(next))
		next++
	}
	args := []string{"-o", toolArg(dst), "--no-date"}
	if !hasTrackStatistics(p) {
		args = append(args, "--disable-track-statistics-tags")
	}
	if chaptersFile != "" {
		args = append(args, "--chapters", toolArg(chaptersFile))
	}
	args = append(args, "--no-chapters")
	if !baseHasTracks {
		args = append(args, "-D", "-A")
	}
	args = append(args, toolArg(base), "--no-global-tags", "--no-track-tags", "--no-chapters", "--no-attachments")
	for i, s := range encoded {
		args = append(args, newTrackArgs(i, s, trackTags[i])...)
	}
	return append(args, toolArg(intermediate), "--track-order", strings.Join(order, ","))
}

// RebuildTrim writes dst: src cut to r, with chapters as computed, and edition written into the
// file when it is non-empty. It does not verify or land anything. On error dst and every working
// file are removed.
func RebuildTrim(ctx context.Context, t Tools, family string, available map[string]bool, src, dst string, p Probe, r trimRange, chapters []Chapter, edition string) (err error) {
	intermediate := src + ".holodex-tmp"
	cut := src + ".holodex-cut.holodex-tmp"
	for _, name := range []string{dst, intermediate, cut} {
		if err := refuseSymlink(name); err != nil {
			return err
		}
	}
	defer func() {
		if err != nil {
			os.Remove(dst)
		}
	}()
	switch family {
	case FamilyMP4:
		format := "mp4"
		if strings.EqualFold(filepath.Ext(src), ".mov") {
			format = "mov"
		}
		chaptersFile := ""
		if len(chapters) > 0 {
			if chaptersFile, err = writeTempFile("holodex-chapters-*.txt", ffmetadataChapters(chapters)); err != nil {
				return err
			}
			defer os.Remove(chaptersFile)
		}
		args, err := TrimMP4Args(p, available, format, src, dst, chaptersFile, r)
		if err != nil {
			return err
		}
		if _, err := run(ctx, t.FFmpeg, args...); err != nil {
			return fmt.Errorf("re-encode: %w", err)
		}
		var extra []string
		if edition != "" {
			tag, _ := writeback.TagForField("edition", "MP4")
			extra = []string{"-" + tag + "=" + edition}
		}
		return restoreMP4Tags(ctx, t, src, dst, format, extra...)
	case FamilyMKV:
		defer os.Remove(intermediate)
		defer os.Remove(cut)
		args, err := TrimMKVEncodeArgs(p, available, src, intermediate, r)
		if err != nil {
			return err
		}
		tags, err := prepareTrackTagFiles(ctx, t, src, p, trimEncoded(p))
		if err != nil {
			return err
		}
		for _, f := range tags {
			if f != "" {
				defer os.Remove(f)
			}
		}
		if _, err := run(ctx, t.FFmpeg, args...); err != nil {
			return fmt.Errorf("re-encode: %w", err)
		}
		base, baseHasTracks := src, false
		if otherTracks(p) > 0 {
			if err := runMkvmerge(ctx, t.Mkvmerge, TrimMKVCutArgs(p, src, cut, r)); err != nil {
				return fmt.Errorf("cut: %w", err)
			}
			base, baseHasTracks = cut, true
		}
		chaptersFile := ""
		if len(chapters) > 0 {
			if chaptersFile, err = writeTempFile("holodex-chapters-*.xml", matroskaChapters(chapters)); err != nil {
				return err
			}
			defer os.Remove(chaptersFile)
		}
		if err := runMkvmerge(ctx, t.Mkvmerge, TrimMKVMergeArgs(p, base, baseHasTracks, intermediate, tags, chaptersFile, dst)); err != nil {
			return fmt.Errorf("rebuild: %w", err)
		}
		if err := restoreMKVDate(ctx, p, dst); err != nil {
			return err
		}
		if edition != "" {
			tag, _ := writeback.TagForField("edition", "Matroska")
			if err := writeback.WriteMatroska(ctx, dst, []writeback.FieldWrite{{TagName: tag, Values: []string{edition}}}); err != nil {
				return fmt.Errorf("write edition: %w", err)
			}
		}
		return nil
	}
	return fmt.Errorf("maintenance: unsupported container family %q", family)
}
